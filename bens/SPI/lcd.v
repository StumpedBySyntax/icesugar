
/* Purpose

The SPI Master shall provide a reusable interface between the FPGA and SPI peripherals, initially targeting an SPI LCD controller.

*/


// The module shall operate exclusively as an SPI master.
// The module shall generate:
// - SCLK
// - CS_N
// - MOSI

// The module shall sample:
// - MISO

/*
| Signal | Full Name                 | Purpose                                  |
|---------|--------------------------|------------------------------------------|
| SCLK    | Serial Clock             | Clock generated by the FPGA             |
| CS_N    | Chip Select (Active Low) | Selects the LCD controller              |
| MOSI    | Master Out, Slave In     | Commands and pixel data to the LCD      |
| MISO    | Master In, Slave Out     | Data returned from the LCD (optional)   |
| DC      | Data/Command             | Distinguishes commands from data        |
| RST_N   | Reset (Active Low)       | Resets the LCD controller               |
*/

/* Input clock 48 MHz */



/* Need a clock divider mechanism. To avoid multiple clock domains, use a clock enable module with divisor
parameter so we can adjust output frequency. Then all other modules will use the main 48 Mhz clock as input */

module clock_enable #(
    // Number of input clock cycles between output tick pulses.
    //
    // Input Clock Frequency : 48 MHz
    // Tick Frequency        : 48 MHz / DIVISOR
    //
    // Examples:
    // DIVISOR = 480  -> 100 kHz tick
    // DIVISOR = 48   ->   1 MHz tick
    // DIVISOR = 24   ->   2 MHz tick
    // DIVISOR = 12   ->   4 MHz tick
    // DIVISOR = 6    ->   8 MHz tick
    //
    // Valid values:
    // DIVISOR >= 1
    //
    // Recommended values for SPI LCD development:
    // 24 .. 480
    //
    parameter integer DIVISOR = 24
)(
    input  wire clk,
    input  wire rst,

    output reg  tick
);

    reg [15:0] counter;

    always @(posedge clk) begin
        if (rst) begin
            counter <= 16'd0;
            tick    <= 1'b0;
        end
        else begin

            // default
            tick <= 1'b0;

            if (counter == (DIVISOR - 1)) begin
                counter <= 16'd0;
                tick    <= 1'b1;
            end
            else begin
                counter <= counter + 1'b1;
            end

        end
    end

endmodule



module spi_master (
    input  wire       clk,
    input  wire       rst,

    // Timing
    input  wire       tick,

    // Control
    input  wire       start,
    output reg        busy,
    output reg        done,

    // Data
    input  wire [7:0] tx_data,
    output reg  [7:0] rx_data,

    // SPI Interface
    output reg        spi_cs_n,
    output reg        spi_sclk,
    output reg        spi_mosi,
    input  wire       spi_miso
);

    // State machine
    // 0 - Idle
    // 1 - Load
    // 2 - Transfer - SHIFT_LOW
    // 3 - Transfer - SHIFT_HIGH
    // 4 - Complete
    localparam IDLE       = 3'd0;
    localparam LOAD       = 3'd1;
    localparam SHIFT_LOW  = 3'd2;
    localparam SHIFT_HIGH = 3'd3;
    localparam COMPLETE   = 3'd4;


    reg [1:0] state;

    // Shift registers
    reg [7:0] tx_shift_reg;
    reg [7:0] rx_shift_reg;

    // Bit counter
    reg [2:0] bit_count;


    always @(posedge clk) begin

        if(rst) begin
            state <= IDLE;
        end
        else begin
            
            CASE (state)

                IDLE: begin
                    // wait for start
                    if (start) begin
                        state <= LOAD;
                    end
                end

                LOAD: begin

                end

                SHIFT_LOW: begin

                end

                SHIFT_HIGH: begin

                end

                COMPLETE: begin
                    
                end

                default: begin
                    state <= IDLE;
                end


        end
    end





endmodule







module lcd_driver (
    input  wire       clk,
    input  wire       rst,

    output wire       spi_cs,
    output wire       spi_clk,
    output wire       spi_mosi,

    output reg        lcd_dc,
    output reg        lcd_rst
);

endmodule