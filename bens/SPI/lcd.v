
/* Purpose

The SPI Master shall provide a reusable interface between the FPGA and SPI peripherals, initially targeting an SPI LCD controller.

*/


// The module shall operate exclusively as an SPI master.
// The module shall generate:
// - SCLK
// - CS_N
// - MOSI

// The module shall sample:
// - MISO

/*
| Signal | Full Name                 | Purpose                                  |
|---------|--------------------------|------------------------------------------|
| SCLK    | Serial Clock             | Clock generated by the FPGA             |
| CS_N    | Chip Select (Active Low) | Selects the LCD controller              |
| MOSI    | Master Out, Slave In     | Commands and pixel data to the LCD      |
| MISO    | Master In, Slave Out     | Data returned from the LCD (optional)   |
| DC      | Data/Command             | Distinguishes commands from data        |
| RST_N   | Reset (Active Low)       | Resets the LCD controller               |
*/

/* Input clock 48 MHz */


module top (
    input  wire clk,
    input  wire rst,

    output wire spi_cs,
    output wire spi_clk,
    output wire spi_mosi,

    output wire lcd_dc,

    output wire led
);

    wire debug_alive;

    lcd_driver lcd0 (
        .clk(clk),
        .rst(rst),

        .spi_cs(spi_cs),
        .spi_clk(spi_clk),
        .spi_mosi(spi_mosi),

        .lcd_dc(lcd_dc),

        .debug_alive(debug_alive)
    );

    assign led = debug_alive;

endmodule




/* Need a clock divider mechanism. To avoid multiple clock domains, use a clock enable module with divisor
parameter so we can adjust output frequency. Then all other modules will use the main 48 Mhz clock as input */

module clock_enable #(
    // Number of input clock cycles between output tick pulses.
    //
    // Input Clock Frequency : 48 MHz
    // Tick Frequency        : 48 MHz / DIVISOR
    //
    // Examples:
    // DIVISOR = 480  -> 100 kHz tick
    // DIVISOR = 48   ->   1 MHz tick
    // DIVISOR = 24   ->   2 MHz tick
    // DIVISOR = 12   ->   4 MHz tick
    // DIVISOR = 6    ->   8 MHz tick
    //
    // Valid values:
    // DIVISOR >= 1
    //
    // Recommended values for SPI LCD development:
    // 24 .. 480
    //
    parameter integer DIVISOR = 24
)(
    input  wire clk,
    input  wire rst,

    output reg  tick
);

    reg [25:0] counter;

    always @(posedge clk) begin
        if (rst) begin
            counter <= 26'd0;
            tick    <= 1'b0;
        end
        else begin

            // default
            tick <= 1'b0;

            if (counter == (DIVISOR - 1)) begin
                counter <= 26'd0;
                tick    <= 1'b1;
            end
            else begin
                counter <= counter + 1'b1;
            end

        end
    end

endmodule



module spi_master (
    input  wire       clk,
    input  wire       rst,

    // Timing
    input  wire       tick,

    // Control
    input  wire       start,
    output reg        busy,
    output reg        done,

    // Data
    input  wire [7:0] tx_data,
    output reg  [7:0] rx_data,

    // SPI Interface
    output reg        spi_cs_n,
    output reg        spi_sclk,
    output reg        spi_mosi,
    input  wire       spi_miso
);

    // State machine
    // 0 - Idle
    // 1 - Load
    // 2 - Transfer - SHIFT_LOW
    // 3 - Transfer - SHIFT_HIGH
    // 4 - Transfer - SHIFT_HIGH Sample
    // 5 - Complete
    localparam IDLE        = 3'd0;
    localparam LOAD        = 3'd1;
    localparam SHIFT_LOW   = 3'd2;
    localparam SHIFT_HIGH  = 3'd3;
    localparam SAMPLE      = 3'd4;
    localparam COMPLETE    = 3'd5;


    reg [2:0] state;

    // Shift registers
    reg [7:0] tx_shift_reg;
    reg [7:0] rx_shift_reg;

    // Bit counter for 1 byte (8 bits)
    // Current bit position (7..0)
    // Begin transmission at bit 7 (MSB)
    reg [2:0] bit_count;


    always @(posedge clk) begin

        done <= 1'b0;

        if(rst) begin
            /*  During reset the state is IDLE, busy and done are both low.
                Slave CS_N is high (disabled)
                spi_sclk is low.
            */
            state <= IDLE;
            busy <= 1'b0;
            done <= 1'b0;
            spi_cs_n <= 1'b1;
            spi_sclk <= 1'b0;

            bit_count <= 3'd7;
            tx_shift_reg <= 8'b0;
            rx_shift_reg <= 8'b0;
            rx_data <= 8'b0;
            spi_mosi <= 1'b0;

        end else begin
            
            case (state)

                IDLE: begin

                    busy <= 1'b0;
                    spi_cs_n <= 1'b1;
                    spi_sclk <= 1'b0;
                    // wait for start

                    if (start) begin
                        state <= LOAD;
                    end
                end

                LOAD: begin
                    tx_shift_reg <= tx_data;
                    rx_shift_reg <= 8'b0;
                    bit_count <= 3'd7;
                    busy <= 1'b1;
                    spi_cs_n <= 1'b0;
                    spi_sclk <= 1'b0;
                    state <= SHIFT_LOW;
                end

                SHIFT_LOW: begin
                    busy <= 1'b1;
                    spi_mosi <= tx_shift_reg[7];
                    spi_sclk <= 1'b0;
                    spi_cs_n <= 1'b0;
                    if (tick) begin
                        state <= SHIFT_HIGH;
                    end

                end

                SHIFT_HIGH: begin
                    busy <= 1'b1;
                    spi_sclk <= 1'b1;
                    spi_cs_n <= 1'b0;
                    if (tick) begin
                        state <= SAMPLE;
                    end
                end


                SAMPLE: begin
                    busy <= 1'b1;
                    spi_sclk <= 1'b1;
                    spi_cs_n <= 1'b0;
                    tx_shift_reg <= {tx_shift_reg[6:0], 1'b0};
                    // Sample the spi_miso
                    rx_shift_reg <= {rx_shift_reg[6:0], spi_miso};
                    if (bit_count == 3'd0)
                        state <= COMPLETE;
                    else begin
                        bit_count <= bit_count - 1'b1;
                        state <= SHIFT_LOW;
                    end


                end

                COMPLETE: begin
                    spi_cs_n <= 1'b1;
                    spi_sclk <= 1'b0;
                    busy <= 1'b0;
                    done <= 1'b1;
                    rx_data <= rx_shift_reg;
                    state <= IDLE;
                    spi_mosi <= 1'b0;
                    
                end

                default: begin
                    state <= IDLE;
                    busy <= 1'b0;
                    done <= 1'b0;
                    spi_cs_n <= 1'b1;
                    spi_sclk <= 1'b0;
                    spi_mosi <= 1'b0;
                end
            endcase
        end
    end

endmodule






module lcd_driver (
    input  wire clk,
    input  wire rst,

    output wire spi_cs,
    output wire spi_clk,
    output wire spi_mosi,
    

    output reg  lcd_dc,
    output reg debug_alive
);


    
    //assign debug_alive = spi_done;

    //---------------------------------------------------------
    // SPI tick generator
    //---------------------------------------------------------

    wire tick;

    clock_enable #(
        .DIVISOR(24)
    ) spi_clk_en (
        .clk(clk),
        .rst(rst),
        .tick(tick)
    );

    //---------------------------------------------------------
    // 1 second timer
    //---------------------------------------------------------

    wire slow_tick;

    clock_enable #(
        .DIVISOR(48_000_000)
    ) sec_timer (
        .clk(clk),
        .rst(rst),
        .tick(slow_tick)
    );

    //---------------------------------------------------------
    // SPI master
    //---------------------------------------------------------

    reg       spi_start;
    reg [7:0] spi_tx_data;

    wire      spi_busy;
    wire      spi_done;

    spi_master spi0 (
        .clk(clk),
        .rst(rst),

        .tick(tick),

        .start(spi_start),

        .busy(spi_busy),
        .done(spi_done),

        .tx_data(spi_tx_data),
        .rx_data(),

        .spi_cs_n(spi_cs),
        .spi_sclk(spi_clk),
        .spi_mosi(spi_mosi),
        .spi_miso(1'b0)
    );

    //---------------------------------------------------------
    // LCD command state machine
    //---------------------------------------------------------

    localparam SEND_SLEEP_OUT   = 3'd0;
    localparam WAIT_SLEEP_OUT   = 3'd1;

    localparam SEND_DISPLAY_ON  = 3'd2;
    localparam WAIT_DISPLAY_ON  = 3'd3;
    localparam HOLD_ON          = 3'd4;

    localparam SEND_DISPLAY_OFF = 3'd5;
    localparam WAIT_DISPLAY_OFF = 3'd6;
    localparam HOLD_OFF         = 3'd7;

    reg [2:0] state;

    always @(posedge clk) begin

        // Default
        spi_start <= 1'b0;

        if (rst) begin
            debug_alive <= 1'b0;

            state <= SEND_SLEEP_OUT;

            lcd_dc <= 1'b0;

            spi_tx_data <= 8'h00;

        end
        else begin

            if (spi_done)
                debug_alive <= ~debug_alive;

            case (state)

                //-------------------------------------------------
                // 0x11 Sleep Out
                //-------------------------------------------------

                SEND_SLEEP_OUT: begin

                    lcd_dc <= 1'b0;      // Command

                    if (!spi_busy) begin
                        spi_tx_data <= 8'h11;
                        spi_start   <= 1'b1;
                        state       <= WAIT_SLEEP_OUT;
                    end

                end

                WAIT_SLEEP_OUT: begin

                    if (spi_done)
                        state <= SEND_DISPLAY_ON;

                end

                //-------------------------------------------------
                // 0x29 Display ON
                //-------------------------------------------------

                SEND_DISPLAY_ON: begin

                    lcd_dc <= 1'b0;      // Command

                    if (!spi_busy) begin
                        spi_tx_data <= 8'h29;
                        spi_start   <= 1'b1;
                        state       <= WAIT_DISPLAY_ON;
                    end

                end

                WAIT_DISPLAY_ON: begin

                    if (spi_done)
                        state <= HOLD_ON;

                end

                //-------------------------------------------------
                // Hold ON for 1 second
                //-------------------------------------------------

                HOLD_ON: begin

                    if (slow_tick)
                        state <= SEND_DISPLAY_OFF;

                end

                //-------------------------------------------------
                // 0x28 Display OFF
                //-------------------------------------------------

                SEND_DISPLAY_OFF: begin

                    lcd_dc <= 1'b0;      // Command

                    if (!spi_busy) begin
                        spi_tx_data <= 8'h28;
                        spi_start   <= 1'b1;
                        state       <= WAIT_DISPLAY_OFF;
                    end

                end

                WAIT_DISPLAY_OFF: begin

                    if (spi_done)
                        state <= HOLD_OFF;

                end

                //-------------------------------------------------
                // Hold OFF for 1 second
                //-------------------------------------------------

                HOLD_OFF: begin

                    if (slow_tick)
                        state <= SEND_DISPLAY_ON;

                end

                default: begin

                    state <= SEND_SLEEP_OUT;

                end

            endcase

        end

    end

endmodule



